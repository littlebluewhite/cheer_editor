				<h4>加隊員</h4>
				<p class="purpose">把會上場的人放進名單。</p>
				<ol class="steps">
					<li>在「名字」框打名字。一次加很多人：打完一個名字按 Enter 換行，再打下一個（Enter 只會換行，不會送出）。</li>
					<li>選「性別」和「全局角色」（底層或上層）。這兩個會套用到這次只打名字的每個人，所以同性別、同全局角色的人一起加最快。加完不會清掉，下一批一樣就不用再選；不一樣記得改。</li>
					<li>按「加隊員」。</li>
				</ol>
				<p class="note">
					<b>從試算表貼：</b>名單在試算表裡有「名字、性別、全局角色」三欄時，選起來複製，直接貼進「名字」框：一行一個人，三欄用 Tab 隔開。性別寫「男」或「女」，全局角色寫「底層」或「上層」；這種行用自己的性別和全局角色，不看下面的選單。只打名字的行和三欄的行可以混在一起。<br />
					<b>加不進去的行：</b>名字空的、太長（最多 20 個字）、性別或全局角色寫錯的行不加，原因一次全部列出（例如「第 2 行「阿強」：性別要寫「男」或「女」」），那幾行留在框裡讓你改；其他行照常加。加了會超過 40 人時一個都不加，寫「只能再加 N 人」。
				</p>
				<p class="note">名單裡有兩個人同名時，名單上面會出現黃字提醒（不擋）：泳道和動作表單只寫名字，分不出誰是誰，可以加個字分開，例如「王小明 A」。</p>
				<p class="note">
					新加的人會直接排進場：在開頭那張站位裡，站到最靠近場地正中心、還沒有人的格點（格線的交點），後面每張站位也先站在同一個位置。場地的格點都站滿了，才排到場地外。之後再拖到你要的位置（見 <a href="#formations">4.5</a>）。最多 40 人。名單順序就是圓點上的號碼和泳道的順序，之後可以調（見下面的「排順序」）。圓點上的標記想寫開頭字（名字的第一個字）、不寫號碼，到「流程設定」換（見 <a href="#settings">4.8</a>）。
				</p>

				<h4>改隊員</h4>
				<p class="purpose">改名字、性別、全局角色。候補上場時，就把被換下的人改成候補的名字：站位和動作都會跟著這個人，不用重排。</p>
				<ol class="steps">
					<li>在名單裡直接改名字欄，或改性別、全局角色的下拉選單。</li>
				</ol>
				<p class="note">他有成功率紀錄時，改名字會先問要「保留舊紀錄」還是「清掉重算」；刪隊員會清掉他所在的組的紀錄（見 <a href="#practice">4.10</a>）。</p>

				<h4>排順序</h4>
				<p class="purpose">名單的順序就是泳道的順序，也是圓點上的號碼（標記是「號碼」時）。</p>
				<ol class="steps">
					<li>按那個人右邊的「↑」往上移一個、「↓」往下移一個；或按住名單最左邊的圓圈（他的標記），拖到另一列放開。</li>
				</ol>
				<p class="note">號碼跟著新的順序變：場地、泳道、八拍表上的號碼都會換。站位、動作還是跟著這個人，不用重排。可以復原。</p>

				<h4>刪隊員</h4>
				<ol class="steps">
					<li>按那個人右邊的垃圾桶。</li>
					<li>那一列下面會先問你：寫他的名字、標記、全局角色，和他在幾個動作裡（不在任何動作裡就寫「他不在任何動作裡」）；只有他一個人的動作會整個被刪掉，那些動作會列出來。他在留下來的動作裡是上層時，會寫那個動作「會少了上層」。有拍點會跟著拿掉（給他本人的；還有給某個任務角色、而那個角色在動作裡只有他的），也會寫「會一起拿掉 N 個拍點」。確定才按確定。</li>
				</ol>
			</section>

			<section id="segments">
				<h3 class="sec">4.3 段</h3>
				<p class="where">在<b>時間軸的段列</b>和<b>段設定</b>操作。</p>

				<h4>加段</h4>
				<p class="purpose">把流程的時間一段一段排出來。照真正表演的順序加。</p>
				<ol class="steps">
					<li>要加在最後：按段列最左邊「段」旁的「＋」。要插在中間：按那一段右邊邊緣上的小「＋」（滑鼠移過去寫「加在音樂 1 後面」），新段就插在它後面。</li>
					<li>選「＋音樂段」或「＋口號段」。段設定自動打開。</li>
				</ol>
				<p class="note">新的音樂段預設 150 BPM、8 個八拍；新的口號段預設 10 秒。段的名字照順序自動取（音樂 1、口號 1…），不能改；插段、換順序之後，名字跟著重新編號。在段設定最下面按「往前移」「往後移」換順序，按「刪除這一段」刪掉。段裡的動作、站位跟著段走；刪段時段裡有東西會先列出來問你。都可以復原。還沒有段時，上方列的播放鍵是灰的（滑鼠移過去寫「先加一段」）。</p>

				<h4>設定音樂段</h4>
				<p class="purpose">讓編輯器知道音樂從哪一刻開始數「1」、多快，這樣八拍尺、節拍器、動作的時間才會對到音樂。</p>
				<figure class="diagram shot">
					<a href={segmentShot} target="_blank" rel="noopener"
						><img src={segmentShot} style:max-width="680px" alt="音樂段的段設定：1 載入音樂檔、2 BPM、3 第一拍（秒）、4 波形（粗線是第一拍，細線是每一拍）、5 試聽按鈕、6 長度。" /></a
					>
					<figcaption>圖 8　音樂段的段設定。① 「載入音樂檔」　② BPM　③ 第一拍（秒）　④ 波形：橘紅粗線是第一拍，細線是每一拍，細線對準鼓點就對了　⑤ 試聽　⑥ 長度。</figcaption>
				</figure>
				<ol class="steps">
					<li><b>打開段設定：</b>點段列上那一段。</li>
					<li><b>載入音樂檔：</b>按「載入音樂檔」，選 mp3、m4a 或 wav。載入後會畫出波形：畫的是這一段用到的那一截，從第一拍到段尾。音樂檔壞了、讀不出來時，寫「音樂檔壞了，請重新選檔」。</li>
					<li><b>填 BPM：</b>在「速度和第一拍」那一區的「BPM」打數字。超出範圍會被擋下：框退回原本的數字，下面寫「「BPM」退回原本的值：BPM 要在 60 到 170 之間」。</li>
					<li><b>對第一拍：</b>在波形上點你開始數「1」的那個鼓點。橘紅粗線就是第一拍，後面的細線是照 BPM 算出來的每一拍，比較亮的是每個八拍的開頭。<b>細線一直對準鼓點，BPM 和第一拍就都對了</b>；越後面越偏，就是 BPM 不對。也可以直接在「第一拍（秒）」打數字。</li>
					<li><b>試聽：</b>按「▶ 從第一拍聽 2 個八拍」，節拍器的聲音應該跟音樂的拍一起。按鈕變成「■ 停止試聽」，再按一次就停；關掉段設定也會停。</li>
					<li><b>設長度：</b>按「照音樂長度算」，或自己填「八拍數」（1 到 200）和「最後一個八拍有幾拍」（最後一個八拍可以不滿 8 拍）。</li>
					<li>段比音樂檔長時（從第一拍算），「長度」下面出現黃字「這一段比音樂檔長 X 秒」：最後那一段播放時沒有聲音。只提醒，不擋。</li>
					<li>按右上角的 ×、按 Esc 或點視窗外面關閉，三種結果一樣：改對的留著；打錯、被擋下的那一格退回原本的值，視窗先不關，寫出是哪一格退回、為什麼，再關一次就關掉。段設定開著時，播放中的音樂可以按右上角的「暫停」或空白鍵停下來。</li>
				</ol>
				<p class="note">
					要注意：沒有音樂檔也可以先排，播放時只有節拍器的聲音。音樂中途變速時，加第二個音樂段，在段設定的「用已載入的音樂」（已經有別的段載入音樂時才有這個選單）選同一個音樂檔：<b>第一拍會自動接在前一段的結尾</b>（前一段的第一拍加上它的長度），只要再對那一段自己的 BPM，第一拍差一點再微調。
				</p>

				<h4>設定口號段</h4>
				<ol class="steps">
					<li>點段列上的口號段。</li>
					<li>在「長度（秒）」打秒數，最細 0.1 秒，最長 300 秒。</li>
				</ol>

				<h4>把段縮短</h4>
				<p class="note">
					段縮短後，放不進去的動作或站位會被刪掉。畫面會先列出哪些會被刪，你按確定才改；按取消就回到原本的長度。
				</p>

				<h4>找不到音樂</h4>
				<p class="note">
					段列上紅色、寫「找不到音樂」的段，表示流程檔裡少了那個音樂檔。點那一段，按「載入音樂檔」重新選。動作和站位都不會動。
				</p>
			</section>

