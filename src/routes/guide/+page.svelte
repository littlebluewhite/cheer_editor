					<a href={timelineShot} target="_blank" rel="noopener"
						><img src={timelineShot} style:max-width="760px" alt="時間軸：1 段列、2 八拍尺、3 站位列、4 泳道、5 播放頭（橘紅色直線）、6 小美泳道下緣的走位條。" /></a
					>
					<figcaption>圖 9　時間軸。① 段列　② 八拍尺　③ 站位列　④ 泳道　⑤ 播放頭　⑥ 走位條（小美從站位 1 的位置走位到站位 2 的位置）。</figcaption>
				</figure>

				<h4>移動播放頭</h4>
				<ol class="steps">
					<li>在八拍尺上點一下，播放頭就跳到那裡；按住拖可以慢慢找。音樂段會停在整拍上（例如「4-1」）；要停在半拍「4-1&amp;」，按著 Option（Windows：Alt）再點。點在八拍的號碼上，就停在那個八拍的第 1 拍。點的地方很靠近一張站位時，先停到那張站位上。</li>
					<li>鍵盤的 ← → 一次移一拍（口號段 1 秒）；按著 Shift 跳到上一個、下一個八拍的 1（口號段 5 秒）。Home 跳到流程開頭，End 跳到結尾。</li>
					<li>看上方列的目前位置，確認在你要的那一拍，例如「音樂 1 3-1」。差一點就再點一次。</li>
				</ol>

				<h4>播放、暫停</h4>
				<ol class="steps">
					<li>按上方列的圓形播放鍵。從播放頭開始播；已經播到最後就從頭播。</li>
					<li>再按一次暫停。</li>
				</ol>
				<p class="note">也可以按空白鍵。但空白鍵跟一般網頁一樣，會先給<b>焦點所在的東西</b>：游標在輸入框裡（例如剛打完名字）時只會打出空格；焦點停在按鈕、勾選框、選單上（例如剛按過「加隊員」）時，是按下那個按鈕。這時先點一下場地或時間軸的空白處再按。段設定開著時，空白鍵也能暫停。還沒有段時播放鍵是灰的。</p>

				<h4>節拍器</h4>
				<p class="purpose">播放時每一拍響一聲，每個八拍的「1」比較重。按上方列的「節拍器」開或關。</p>

				<h4>延遲校正（毫秒）</h4>
				<p class="purpose">
					用藍牙耳機或喇叭時，聲音會比畫面慢一點。覺得畫面比聲音快，就把這個數字調大（每次加 10 試試）。這個數字只存在這台電腦，不會存進流程檔。
				</p>

				<h4>時間軸放大、縮小</h4>
				<p class="purpose">八拍尺左邊「八拍」旁的「−」「＋」，中間的數字是目前倍數（例如「×1」）。也可以把滑鼠放在時間軸上，按住 Ctrl（Mac 按 ⌘）滾滾輪，或在觸控板上兩指捏合。放大看得清楚每一拍，縮小看得到整支流程。按「＋」旁邊的「符合寬度」，整支流程剛好放滿現在的時間軸寬度。</p>
			</section>

