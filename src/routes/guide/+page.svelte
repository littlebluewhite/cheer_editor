					<li><b>新建流程：</b>取名字，選場地（幾條、直放或橫放）。場地<b>建好之後不能換</b>，先確認比賽用哪種。</li>
					<li><b>加隊員：</b>把會上場的人加進名單。名單的順序就是泳道的順序，也是場地圓點上的號碼（預設的標記）；之後也可以在名單上調順序。新加的人直接排進場地中間的空位。</li>
					<li><b>加段：</b>照真正表演的順序，一段一段加在最後面。音樂段要載入音樂檔、對好第一拍和 BPM。</li>
					<li><b>排站位：</b>把播放頭移到某一拍，在場地上拖隊員。拖完，那一拍就有一張站位；兩張站位之間，隊員會自己走位。站位放錯拍，挪站位就好，不用重拖。</li>
					<li><b>加動作：</b>把播放頭移到動作開始的那一拍，選人、選大類、填長度、給每個人任務角色（點選單後按數字鍵就選好、跳到下一個人；滑鼠移到「!」看全部快捷鍵和名字顏色的意思）。</li>
					<li><b>播放檢查：</b>從頭播一次，看場地上的人怎麼走、泳道上誰在做什麼。不對就回第 2–5 步改。</li>
					<li><b>存檔：</b>得到一個流程檔。上方列流程名字旁邊的「未存」消失，就是存好了。</li>
					<li><b>分享：</b>把流程檔傳給隊員，或印八拍表。</li>
				</ol>
			</section>

