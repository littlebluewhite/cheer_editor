				<h4>拖人（排站位）</h4>
				<ol class="steps">
					<li>把播放頭移到你要的那一拍（見 <a href="#playback">4.4</a>）。</li>
					<li>拖之前，看左邊欄「跟上一張一樣」下面那一行字，它告訴你這次會改哪一張站位：「拖人會改：站位 3（2-1）」、「拖人會改：站位 1（開頭）」，或「拖人會在 2-3 插一張新站位」。站位的號碼跟站位列小圖左上角的號碼一樣；口號段寫秒數。</li>
					<li>在場地上按住一個隊員，拖到新位置，放開。</li>
					<li>那一拍原本就有站位，就改那張；沒有，就插一張新的，其他人的位置自動帶入，就是他們在那一拍本來所在的位置（提示會寫「插了一張站位，大家的位置自動帶入」）。</li>
				</ol>
				<p class="note">兩個人被拖到同一點時，左邊欄出現黃字「小A、小B 疊在同一點」：被蓋住的人看不到也點不到，拖開一點比較好。只提醒，不擋。</p>
				<p class="note">
					<b>往後帶：</b>你改了一個人的位置，後面的站位裡他如果還站在舊位置，會一起改到新位置，不用一張一張重拖。編輯器往後一張一張看，遇到第一張他已經不在舊位置的就停，後面排好的不會被動到。有往後帶到時，提示會寫「後面 2 張站位也跟著改了」；同時插了站位，就合成一則：「插了一張站位，大家的位置自動帶入；後面 2 張站位也跟著改了」。
				</p>
				<p class="note">
					<b>跟上一張一樣：</b>先選人（場上點人、拖框選人（見下面的「選取隊員」），或用「動作」分頁的「選人」那一區），再按左邊欄下面的「跟上一張一樣」，選到的人就回到上一張站位的位置，不用一個一個拖回去。播放頭在站位上，就改那張；播放頭不在站位上，會跟拖人一樣先插一張站位，效果就是「他們到這一拍都還站著」。改完一樣會往後帶，提示也跟拖人一樣；整個操作算復原的一步。沒選人時按鈕按不下去，旁邊寫「先選人」；播放頭在開頭那張時，旁邊寫「開頭那張前面沒有站位」。
				</p>
