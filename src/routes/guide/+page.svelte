				<h3 class="sec">4.5 站位</h3>
				<p class="where">在<b>場地</b>和<b>時間軸的站位列</b>操作。</p>
				<p>
					站位是「某一拍全隊站在哪裡」。你不用先「新增一張站位」：<b>只要把播放頭移到那一拍，在場地上拖人，站位就有了</b>。兩張站位之間，每個人最多走位一次：<b>沒設的人先站著，最後一個八拍才出發</b>，直線、平均速度，剛好在下一張站位那一拍到達。兩張站位之間不到一個八拍，或下一張站位在口號段（沒有拍可以數）時，就從前一張站位那一拍出發，從頭到尾慢慢走。兩張站位裡位置一樣的人，從頭到尾站著不動。
