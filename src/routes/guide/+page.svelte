				<ol class="steps">
					<li>按上方列的「八拍表」。</li>
					<li>在「印誰」選全隊，或只選一個隊員（只列他有參加的動作，小站位圖上他的點塗成深色）。全隊的表在標題下面印場上標記和名字的對照，例如「1 小A　2 小B」。</li>
					<li>
						一列一個八拍。連著好幾個沒有新東西（動作、站位、走位、拍點）的八拍合成一列，「八拍」那一欄寫範圍，例如「5–8」；口號段一整段一列。動作寫在「拍／動作」那一欄、它開始的那一列：最前面是它從這個八拍的第幾拍開始，接著是大類·名稱（名稱跟大類一樣，例如名稱就叫「舞蹈」的舞蹈，只寫一次），再來是每個人和任務角色。全隊都在這個動作裡時寫「全隊」，有人有任務角色就接著列出來，例如「全隊：小A（上層）、小B（主底）」。只印一個隊員時不重複寫他的名字，只寫他的任務角色、第幾組和同組的人，例如「主底・第 2 組・同組：小A（上層）、小D（側底）」。小站位圖只畫有人站的那一塊，人多時也看得清楚；下面寫「站位 2 開場・第 1 拍」：站位號碼、站位名稱和第幾拍。
					</li>
					<li>只印一個隊員時，他每換一次位置，就在出發那一拍所在的那一列多寫一行，例如「2-5 出發 → 站位 3（3-1 到達）」：哪一拍出發、到哪一張站位、哪一拍到達。不寫「走」，因為他可能是跑、也可能是騰翻。出發或到達在別的段時，時間前面加段名，例如「音樂 1 1-1 到達」。</li>
