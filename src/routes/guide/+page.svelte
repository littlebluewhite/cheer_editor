				<h3>2.1 啦啦隊的詞</h3>
				<div class="table-wrap">
					<table>
						<thead><tr><th>詞</th><th>意思</th></tr></thead>
						<tbody>
							<tr class="group"><td colspan="2">時間</td></tr>
							<tr><td><b>流程</b></td><td>一支隊伍從開始到結束的完整編排，由一串<b>段</b>依序接成。不含進場和退場。</td></tr>
							<tr><td><b>段</b></td><td>流程裡的一個時間區塊。只有兩種：音樂段、口號段。段的名字自動取，例如「音樂 1」「口號 1」。</td></tr>
							<tr><td><b>音樂段</b></td><td>跟著一個音樂檔表演的段，有自己的 BPM 和第一拍，長度用八拍算。音樂中途變速時，切成兩個音樂段。</td></tr>
							<tr><td><b>口號段</b></td><td>沒有音樂、隊員喊出口號的段，長度只用秒數算，不數八拍。</td></tr>
							<tr><td><b>八拍</b></td><td>連續 8 拍算 1 個八拍，是排時間的主要單位。</td></tr>
							<tr><td><b>BPM</b></td><td>每分鐘幾拍。120 BPM 就是一秒兩拍。</td></tr>
							<tr><td><b>第一拍</b></td><td>音樂段在音樂檔裡開始數拍的那個時間點（第幾秒）。</td></tr>
							<tr class="group"><td colspan="2">場地</td></tr>
							<tr><td><b>場地</b></td><td>表演用的體操墊範圍，由幾條併成。場地外 1 公尺內，隊員也能站。</td></tr>
							<tr><td><b>條</b></td><td>一條體操墊。場地大小用「幾條」算。</td></tr>
							<tr><td><b>鋪向</b></td><td>條的鋪法：<b>直放</b>是每條從前鋪到後，<b>橫放</b>是每條從左鋪到右。</td></tr>
							<tr><td><b>正面</b></td><td>場地朝裁判的那一邊。畫面上永遠在下面，寫著「▼ 正面／裁判 ▼」。</td></tr>
							<tr><td><b>接縫</b></td><td>相鄰兩條之間的線，隊員在場上看得到，用來對位置。</td></tr>
							<tr><td><b>格</b></td><td>場地上的一個正方形，邊長等於一條的寬。一條剛好 7 格長，所以可以用「第幾條、第幾格」講位置。</td></tr>
							<tr><td><b>吸附</b></td><td>放開時自動對齊到最近的點：隊員對齊格線或幾分之一格；色條和走位條對齊半拍（口號段是 0.1 秒）。</td></tr>
							<tr class="group"><td colspan="2">人和角色</td></tr>
							<tr><td><b>隊員</b></td><td>流程裡的一個人，有名字、性別、全局角色。只放會上場的人；候補要上場時，把被換下的隊員改成他的名字。一支流程最多 40 人。</td></tr>
							<tr><td><b>標記</b></td><td>寫在隊員圓點上、讓你認出是誰的短字。整支流程用同一種：<b>號碼</b>（名單上第幾個，預設）或<b>開頭字</b>（名字的第一個字）。在「流程設定」換（見 <a href="#settings">4.8</a>）。</td></tr>
							<tr><td><b>全局角色</b></td><td>隊員在整支流程裡固定的身分，只分<b>底層</b>和<b>上層</b>。它決定場地上圓點的顏色（圖例的「底層」「上層」），也決定「全部底層」「全部上層」按鈕選到誰。</td></tr>
							<tr>
								<td><b>任務角色</b></td>
								<td>
									隊員在<b>某一個動作</b>裡要做的事，每個動作可以不同，也可以沒有。跟全局角色互不影響：全局角色是底層的人，在某個金字塔裡可以當中層。
									<b>「底層」「上層」既是全局角色，也是任務角色的名字</b>：全局的上層是整支流程固定的身分；任務的上層是在這一個動作裡被撐起來的人。
								</td>
							</tr>
							<tr class="group"><td colspan="2">任務角色的名稱（編輯器固定有這 11 個，也可以自訂，叫<b>自訂任務角色</b>）</td></tr>
							<tr><td><b>底層</b></td><td>在下面撐住別人的人。不想分主底、側底時用這個。</td></tr>
							<tr><td><b>主底</b></td><td>主要撐住上層腳的底層。只有一個底層的技巧，那個人就是主底。</td></tr>
							<tr><td><b>側底</b></td><td>在主底旁邊一起撐的底層。</td></tr>
							<tr><td><b>上層</b></td><td>被撐在最上面的人。</td></tr>
							<tr><td><b>中層</b></td><td>金字塔裡站在底層身上、又撐住上面的人的人。</td></tr>
							<tr><td><b>保護</b></td><td>站在旁邊保護上層的人。可以扶腳踝、小腿、膝蓋，不能撐腳底，不算底層。</td></tr>
							<tr><td><b>前保</b></td><td>站在上層前方的保護。</td></tr>
							<tr><td><b>後保</b></td><td>站在上層背後的人。</td></tr>
							<tr><td><b>接者</b></td><td>接住落下或被拋的上層的人。</td></tr>
							<tr><td><b>支撐</b></td><td>金字塔裡穩住別的上層的人。</td></tr>
							<tr><td><b>騰翻</b></td><td>做騰翻的人。騰翻是自己完成、沒人撐的翻滾（也是動作的一個大類）。</td></tr>
							<tr class="group"><td colspan="2">動作和位置</td></tr>
							<tr><td><b>動作</b></td><td>一群隊員在一個段裡一起做的一件事，有開始的時間和長度。可以一個人，也可以全隊。<b>動作不能跨段</b>；一個隊員同一時間只能在一個動作裡。</td></tr>
							<tr><td><b>大類</b></td><td>動作屬於哪一種，只有七個：技巧、金字塔、拋投、騰翻、跳躍、舞蹈、其他。</td></tr>
							<tr><td><b>辨識色</b></td><td>你幫一個動作挑的顏色，讓它在泳道上好認。沒挑就用大類的顏色。</td></tr>
							<tr><td><b>站位</b></td><td>全隊在流程某一拍各站在場地哪裡，像一張圖。流程開頭一定有一張。每張站位有號碼（站位 1、站位 2…照時間排）。</td></tr>
							<tr><td><b>站位名稱</b></td><td>你幫一張站位取的名字，例如「開場」「金字塔」。可以不取；取了名字，號碼也不變。</td></tr>
							<tr><td><b>站位時間</b></td><td>一張站位在流程裡的那一拍。沒自己設出發和到達的人，就在這一拍到達。</td></tr>
							<tr><td><b>挪站位</b></td><td>改一張站位的站位時間，大家的位置不變（見 <a href="#formations">4.5</a>）。</td></tr>
							<tr><td><b>自動帶入</b></td><td>在沒有站位的那一拍拖人，會插一張新站位；其他人站在他們那一拍本來所在的位置（見 <a href="#formations">4.5</a>）。</td></tr>
							<tr><td><b>往後帶</b></td><td>改了一個人的位置，後面的站位裡他如果還站在舊位置，也一起改到新位置（見 <a href="#formations">4.5</a>）。</td></tr>
							<tr><td><b>走位</b></td><td>隊員從一張站位的位置直線走到下一張站位的位置。走位不是動作，可以邊做動作邊走位。兩張站位之間，每個人最多走位一次。</td></tr>
							<tr><td><b>出發</b></td><td>隊員開始走位的那一拍。出發之前，他站在前一張站位的位置不動。</td></tr>
							<tr><td><b>到達</b></td><td>隊員走位、到了新位置的那一拍。可以比站位時間早，早到的人站著等。</td></tr>
							<tr><td><b>影子</b></td><td>場地上淡淡的點，標出隊員在上一張站位的位置。</td></tr>
							<tr><td><b>走位線</b></td><td>場地上從走位起點畫到終點的線。正常是白色；很喘（跑得到但很累）是橘色；走太快（跑不到）是紅色。</td></tr>
							<tr><td><b>走位條</b></td><td>泳道下緣的深色細條，一次走位一條，左端是出發、右端是到達。顏色跟走位線一樣標橘、標紅。</td></tr>
								<tr><td><b>撞位</b></td><td>兩個隊員在同一時間靠得太近、會撞上（兩人中心距離不到半格，剛好半格不算），而且至少一個人正在騰翻中走位：在他自己參加的騰翻動作時間裡（助跑也算），而且在出發之後、到達之前。另一個人站著、在一般走位或也在騰翻都算；一般走位、原地騰翻不算。音樂段每半拍、口號段每 0.1 秒看一次，連續好幾次都撞到只算一次。場地上在那個位置畫紫色 ✕，兩個人的走位條撞到的那段變紫色。只提醒，不擋（見 <a href="#formations">4.5</a>）。</td></tr>
							<tr class="group"><td colspan="2">拍點（見 <a href="#cues">4.7</a>）</td></tr>
							<tr><td><b>拍點</b></td><td>動作裡從某一拍開始、佔幾拍的一個提示，寫隊員在那幾拍要喊或要做的事。只有音樂段的動作有拍點，可以給全部的人、某個任務角色或某個隊員。分三種：拍子、步驟、手位。</td></tr>
							<tr><td><b>拍子</b></td><td>跟著拍往下或往上的 down、up 兩個字。down 佔兩拍，就是兩拍都在往下。</td></tr>
							<tr><td><b>步驟</b></td><td>一個動作裡分出來的一段，例如下手、落地、放，可以佔好幾拍。動作自己的名字（例如 Lib）不是步驟。</td></tr>
							<tr><td><b>手位</b></td><td>手臂擺出的固定姿勢，例如 high V、T，只佔一拍。</td></tr>
							<tr class="group"><td colspan="2">成功率（見 <a href="#practice">4.10</a>）</td></tr>
							<tr><td><b>組</b></td><td>一個動作裡一起做、一起算成功率的幾個人，例如一個技巧的主底、側底、後保、上層。一個動作可以有好幾組，例如 16 個人分 4 組同時做一樣的技巧。組號從 1 連續往下排，不跳號：一組空掉，後面的組往前補號，紀錄還是跟著原來那一組。加第一個環節時，全部的人先在第 1 組；大類從騰翻、跳躍換成要分組的大類時也一樣。從別的動作複製人時連組一起帶過來（還沒有環節的動作也帶著），加第一個環節時照帶來的組。動作只有一組時，新加進來、沒帶組的人進第 1 組。沒分到組的人不算成功率。騰翻、跳躍的動作不分組，每個人自己算。</td></tr>
							<tr><td><b>環節</b></td><td>一個動作裡要分開算成功率的一部分。種類只有五種：上法、中段、轉接、下法、整體；可以再取名字，例如上法「延伸」。在音樂段，環節一定佔動作裡的哪幾拍，照拍的先後排；拍被清光，環節就沒了。在口號段不數拍，環節不標拍，照加的先後排。動作有環節才記成功率，最後一個環節沒了就不記。</td></tr>
							<tr><td><b>上法、中段、轉接、下法</b></td><td>上法是把上層撐上去；中段是上層停在上面、不換技巧；轉接是上層在上面換到另一個技巧；下法是讓上層回到地上。</td></tr>
							<tr><td><b>整體</b></td><td>環節的一種：整個動作當成一個環節一起算，例如一次拋投、一趟騰翻。</td></tr>
							<tr><td><b>記號</b></td><td>打在一次的一個環節上的 ✓（成功）、△（小失誤）或 ✗（失敗）。</td></tr>
							<tr><td><b>成功、小失誤、失敗</b></td><td>✓ 乾淨做好；△ 做完了但不乾淨（晃了、快掉，救回來沒掉）；✗ 有做但沒做完（掉下來，被接進搖籃也算）。</td></tr>
							<tr><td><b>一次</b></td><td>一組（騰翻、跳躍是一個人）把一個動作做一遍的紀錄。不是「整個做」，就是「只練幾個環節」。中途失敗，後面的環節空著。</td></tr>
							<tr><td><b>成功率</b></td><td>一個環節有打記號的次數裡，成功佔多少。</td></tr>
							<tr><td><b>完成率</b></td><td>一個環節有打記號的次數裡，成功加小失誤佔多少，也就是沒失敗的比例。</td></tr>
							<tr><td><b>整次成功率</b></td><td>整個做的次裡，每個環節都成功的次佔多少。</td></tr>
							<tr><td><b>全上、分段練</b></td><td>全上是整支流程從頭到尾連著做一遍；分段練是拿一個或連著的幾個動作出來重複練。</td></tr>
							<tr class="group"><td colspan="2">檔案和紙本</td></tr>
							<tr><td><b>流程檔</b></td><td>一支流程存成的一個檔案（<code>流程名字.zip</code>），裡面有全部資料和用到的音樂檔。傳給隊員，隊員用同一個編輯器打開。</td></tr>
							<tr><td><b>草稿</b></td><td>編輯器自動存在<b>這台電腦的瀏覽器</b>裡的備份，防止忘了存檔。不是流程檔，不能傳給別人。</td></tr>
							<tr><td><b>八拍表</b></td><td>把流程照八拍一列一列寫下來的表，每列寫那個八拍開始的動作，有站位的地方附小站位圖。時間都寫成「八拍-拍」，有長度的接「・幾拍」，例如「2-4&amp; 到 2-7&amp;・4 拍」，跟拍點小窗一樣。動作延續到下一個八拍時，那一列多一行灰字「↳ Lib 繼續」。口號段一整段只佔一列；連著好幾個沒有新動作的八拍，也合成一列（例如「5–8」）。可以印全隊的，也可以只印一個隊員的。</td></tr>
						</tbody>
					</table>
