					改流程的操作都能復原：站位、動作、段、隊員、流程設定、名字。一次操作算一步，例如拖一次人（連自動插的站位）、按一次「跟上一張一樣」、新增一個動作、改動作表單的一個欄位。播放頭、選人、放大縮小不算。最多記 100 步；開檔、新建、救回草稿之後就從頭記，關掉或重新整理也會清掉。游標在輸入框裡時，⌘Z／Ctrl+Z 也是復原流程：先把框裡打好的字送出去，再退回上一步，框裡的字跟著變回去。連著按方向鍵移同一批人，合起來算一步。練習記的紀錄不算復原的步，復原不會刪掉它們（見 <a href="#practice">4.10</a>）。復原不動紀錄，紀錄留在原來的組上。
				</p>

