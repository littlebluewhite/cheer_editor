			<section id="cold-read">
				<h2>5 新手試跑</h2>
				<p>
					給<b>完全沒用過</b>的人。先讀完第 1–3 章，再照這一章做一次，大約 20 分鐘，<b>不需要音樂檔</b>。每一步做完，對照「你應該看到」；對不上，就照「卡住了」那一行做，或回去看括號裡的那一節。
				</p>

