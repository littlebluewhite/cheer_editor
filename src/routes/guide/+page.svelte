				<p>
					整份說明、整個編輯器只用下面這些詞，同一件事不會換別的說法。分兩張表：<b>啦啦隊的詞</b>（流程本身的東西）和<b>畫面上的名稱</b>（編輯器的哪個區域、哪個按鈕）。
