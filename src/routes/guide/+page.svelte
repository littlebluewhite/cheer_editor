				<h3 class="sec">4.10 練習：記成功率</h3>
				<p class="where">
					在<b>右邊欄「動作」分頁的動作表單</b>設定要記什麼，在<b>練習畫面</b>記和看。按上方列流程名字旁邊的「練習」切到練習畫面，按「編排」切回來。
				</p>
				<p>
					練習時，教練在旁邊看隊員一組一組做，每做一次，就在每個環節打一個<b>記號</b>：✓ 成功、△ 小失誤、✗ 失敗。記多了，就看得出哪一組、哪個環節不穩。紀錄存在流程檔裡，跟流程一起存檔。
				</p>
				<ul class="plain">
					<li><b>成功（✓）：</b>這個環節乾淨做好。</li>
					<li><b>小失誤（△）：</b>做完了，但不乾淨，例如晃了、快掉，但救回來沒掉。</li>
					<li><b>失敗（✗）：</b>有做，但沒做完，例如掉下來；被接進搖籃也算。</li>
				</ul>

				<h4>先在動作上加環節</h4>
