					<li>按「列印」。在列印視窗可以選印表機，或存成 PDF。長的拍點會換行，不會被切掉；一個八拍的內容太多時可以接到下一頁。</li>
					<li>按「關閉」（或 Esc）回到編輯畫面。</li>
