				<h4>選取隊員、一次拖好幾個人</h4>
				<ol class="steps">
					<li><b>選一個：</b>在場地上點他（或點泳道上他的名字）。選到的人外面會多一圈青色。</li>
					<li><b>選好幾個：</b>按住 Shift 再點；用 iPad 的話，打開場地左邊的「多選」（只有 iPad 上有），再一個一個點（再點一次是拿掉）；或在場地空白的地方按住拖出一個框，框到的人都選起來。</li>
					<li><b>一起拖：</b>拖其中一個人，選到的人全部一起移動，彼此的距離不變。</li>
					<li><b>取消選取：</b>點場地空白的地方，或按 Esc；用 iPad 的話，也可以按場地左邊的「取消選取」（只有 iPad 上有）。</li>
				</ol>
				<p class="note">在這裡選到的人，也就是新增動作時的人（見 <a href="#actions">4.6</a>）。</p>

				<h4>場地放大、縮小</h4>
				<p class="purpose">左邊欄最上面的「−」「＋」，或在場地上滾滑鼠滾輪。按「全場」回到看得到整個場地。</p>

				<h4>設出發和到達（誰先走、誰後走）</h4>
				<p class="purpose">
					預設大家最後一個八拍才出發。要讓幾個人走 16 拍、另外幾個最後 8 拍才出發，或排跑翻的先後順序（10 號、9 號、8 號一個接一個），就替他們設<b>出發</b>和<b>到達</b>。
				</p>
				<ol class="steps">
					<li>把播放頭停在他們要到達的那張站位上（點站位列上的小圖最快）。開頭那張前面沒有站位，所以不會出現「出發和到達」。</li>
					<li>選取要設的隊員。<b>沒選人，就是替全隊有走位的人設</b>（兩張站位位置一樣、站著不動的人不寫進去）。剛加完動作時，那個動作的人可能還選著（外面有青色圈）：要替全隊設，先按 Esc 或「選人」那一區的「不選人」。</li>
					<li>在右邊欄「動作」分頁「選人」下面的「出發和到達」，在「出發」「到達」兩個框打時間，按「套用」（或在框裡按 Enter）。</li>
					<li>要回到最後一個八拍才出發，按「用預設」（清掉選到的人的設定，沒選人就是全隊）。</li>
				</ol>
				<p class="note">
					<b>時間的寫法：</b>跟動作的「開始」一樣，打「2-5」（第 2 個八拍第 5 拍，半拍加 &），口號段打秒數。時間在這張站位那一段以外，前面加段名，例如「口號 1 12.3」（秒數不用打「秒」）。<br />
					<b>早到的人站著等：</b>到達可以早於這張站位，出發可以晚於前一張站位。<br />
					<b>會被擋下來的情況：</b>出發不早於到達、時間不在前一張和這一張站位之間、打的字看不懂。擋下來時「出發和到達」下面寫原因，流程不改。<br />
					選到的人設定不一樣時，框是空的，寫「每人不一樣」；這時出發、到達兩個框都要打才能套用。
				</p>

				<h4>在泳道上拖走位條</h4>
				<p class="purpose">
					每個人每走位一次，他的泳道下緣就有一條深色細條，叫<b>走位條</b>：左端是出發、右端是到達。一眼就看得出誰先走、誰後走。位置沒變的人沒有走位條。
				</p>
				<ol class="steps">
					<li><b>改出發：</b>按住走位條左端拖，放開。</li>
					<li><b>改到達：</b>按住走位條右端拖，放開。</li>
					<li><b>兩端一起挪：</b>按住走位條中間拖，放開。</li>
					<li><b>幾個人一起挪：</b>先選人，再拖其中一人的走位條。選到的人只要在同樣這兩張站位之間有走位條，就一起挪一樣多拍。</li>
				</ol>
				<p class="note">用 iPad：先選人（點他的名字，或點一下他的走位條），他的走位條才拖得動。</p>
				<p class="note">
					拖的時候，走位條上面即時寫新的時間；拖出能放的範圍時，那個小框當下變紅，放開會被擋。<br />
					吸附跟在泳道上拖色條一樣：音樂段吸到半拍，口號段吸到 0.1 秒。放開才改，改一次就是一步，按「復原」退回去。<br />
					走位條不能拖出前一張和這一張站位之間，出發也要早於到達。拖過頭時走位條彈回原位，上方提示寫原因；幾個人一起挪時，只要有一個人過頭，全部都彈回去。
				</p>

				<h4>影子、走位線、走太快標紅、很喘標橘</h4>
				<p class="purpose">場地上看得到誰從哪裡走過來、往哪裡走，走太快的人會標紅、很喘的標橘，你就知道哪裡要多給幾拍。</p>
				<ul class="steps">
					<li><b>播放頭停在站位上</b>（不是開頭那張）：上一張站位的位置畫成淡淡的<b>影子</b>點；位置有變的人，從影子畫一條<b>走位線</b>到他現在的點。</li>
					<li><b>播放頭在兩張站位中間</b>：畫這兩張站位之間的走位線，從前一張的位置畫到後一張的位置，點會沿著線走。</li>
					<li><b>有選人時只畫選到的人</b>；沒選人時畫全隊。人多、線太亂時，先選幾個人看。</li>
					<li><b>只看橘紅走位線：</b>勾左邊欄下面的「只看橘紅走位線」方框，正常的白線藏起來，只留很喘和走太快的線，畫面比較乾淨；取消勾全部回來。</li>
					<li><b>走太快標紅：</b>走位的距離除以出發到到達的秒數，每秒超過 4 公尺（跑不到），場地上的線和泳道上的走位條都變紅。把出發提早或到達延後（多給幾拍）就好了。</li>
					<li><b>很喘標橘：</b>每秒超過 2.5 公尺、沒到 4 公尺，跑得到但會很喘，線和走位條變橘。不一定要改，看他後面接什麼動作再決定。</li>
				</ul>
				<p class="note">
					他走位的時間如果跟他自己參加的、大類是<b>騰翻</b>的動作重疊（例如跑翻），就不標紅也不標橘，因為翻滾本來就比走路快。<br />
					影子和線不擋滑鼠：點人、拖人、框選都跟平常一樣。八拍表上的小站位圖不畫影子和線。<br />
					「每秒 4 公尺」「每秒 2.5 公尺」這兩個數字，之後可能會調整。
				</p>

				<h4>撞位（紫色 ✕）</h4>
				<p class="purpose">
					騰翻的路線上會不會撞到人，編輯器幫你看。<b>撞位</b>是兩個隊員在同一時間靠得太近（兩人中心距離不到半格，剛好半格不算），而且至少一個人正在騰翻中走位：在他自己參加的騰翻動作時間裡（助跑也算在騰翻動作裡），而且在出發之後、到達之前。另一個人站著、在一般走位或也在騰翻都算。一般走位跟別人靠很近是常有的事，不算撞位；原地騰翻（位置沒變）也不算。音樂段每半拍、口號段每 0.1 秒看一次，連續好幾次都撞到只算一次，記在兩人最近的那一刻。
				</p>
				<ul class="steps">
					<li><b>場地上：</b>播放頭在站位上或兩張站位中間時，這一段走位裡撞到的地方畫一個紫色 ✕（左邊欄「只看橘紅走位線」下面的圖例也有）。滑鼠移到 ✕ 上，寫是誰撞到。</li>
					<li><b>泳道上：</b>兩個人的走位條，撞到的那一段變紫色。</li>
				</ul>
				<p class="note">只提醒，不擋。要避開，就改其中一個人的出發、到達（見上面的「設出發和到達」），或把他在站位裡的位置拖開一點，或把騰翻動作挪開。站著不動的兩個人疊在一起不算撞位，那是左邊欄的「疊在同一點」。</p>

				<h4>看、刪站位</h4>
				<ol class="steps">
					<li>點站位列上的小圖：選到那張站位，播放頭跳過去。兩張站位靠得很近時，前一張小圖會變窄，不蓋到後一張；想看大一點，按八拍尺左邊的「＋」放大時間軸。</li>
					<li>要刪：滑鼠移到小圖上，按右上角出現的 ×，或選到後按 Delete（Mac 是 delete 鍵；選好之後又拖人改了別張站位，選取會清掉，免得刪到沒在看的那張）。<b>不會先問，按了就刪</b>；場地下面跳出「已刪掉站位 N」，旁邊有「復原」，按了就救回來（跟按上方列的「復原」一樣）。刪的是拖人時自動插入、又順便改了後面站位的那張，提示會加一句「後面站位的改動還在，要整個還原按復原」：刪掉它不會把後面站位改回去，要整個退回拖人之前，按兩次「復原」（先救回這張，再退掉那次拖人）。提示 10 秒後自己收掉（滑鼠在提示上時不收），之後還是可以按上方列的「復原」。</li>
				</ol>
				<p class="note">要注意：流程開頭那張站位（站位 1）一定在，不能刪。</p>

				<h4>幫站位取名</h4>
				<ol class="steps">
					<li>播放頭停在那張站位上（點站位列上的小圖最快）。</li>
					<li>在左邊欄的<b>站位名稱</b>框（寫著「幫這張站位取名（可不填）」）打名字，例如「開場」「金字塔」，按 Enter。按 Esc 是不改。</li>
				</ol>
				<p class="note">取了名字，左邊欄的「現在站位」、站位列的小圖和八拍表都會寫出來；號碼不變。把框清空就拿掉名字。</p>

				<h4>挪站位（把站位移到別的拍）</h4>
				<p class="purpose">
					站位放錯拍時用：只改這張站位的站位時間，大家在場上的位置不變，不用重拖。例如發現大家其實 5-1 就該站好，不用等到 6-1。
				</p>
				<ol class="steps">
					<li><b>拖小圖：</b>按住站位列上那張小圖，左右拖，小圖上會寫新的站位時間（例如「5-1」），放開就挪過去。只是點一下、或手滑了一點點（不到 10 px）不會挪。</li>
					<li>
						<b>或打時間：</b>播放頭停在那張站位上，在左邊欄「站位時間」那個框打新的時間（寫法跟動作的「開始」一樣，例如「5-1」；別的段前面加段名，例如「口號 1 12.3」），按 Enter。按 Esc 是不改。
					</li>
					<li>挪好，播放頭跟著跳到新的站位時間；場地下面跳出「站位 2 改到 5-1」，旁邊有「復原」。挪錯了按「復原」（或上方列的「復原」），站位回原本的時間，播放頭也跟著回去。</li>
				</ol>
				<p class="note">
					<b>能挪到哪：</b>只能挪到前一張站位之後、後一張站位之前（最後一張是流程結尾之前），所以站位的順序和號碼不會變。「站位時間」框下面寫著可以挪的範圍，例如「可以挪到 3-1 之後、8-1 之前」；最後一張只寫「可以挪到 3-1 之後」。開頭那張不能挪，框是灰的。<br />
					<b>被擋下來：</b>挪過頭時小圖彈回原位，提示寫原因和「已還原」，流程不改。<br />
					<b>走位跟著挪：</b>沒自己設出發和到達的人，照預設在新的站位時間到達。自己設過的，走位長度不變、整段跟著挪；往前挪碰到前一張站位，就從前一張出發，走一樣久再等到站位時間；連長度都放不下，才縮成從前一張走到新的站位時間。有人的走位因此變短時，提示加一句「走位被壓短：小美、阿強」，記得看有沒有變紅（見上面的「走太快標紅」）。<br />
					<b>動作和拍點不會跟著挪。</b>挪一次算復原的一步。
				</p>
			</section>

			<section id="actions">
				<h3 class="sec">4.6 動作</h3>
				<p class="where">在<b>右邊欄的「動作」分頁</b>和<b>泳道</b>操作。</p>

				<h4>新增動作</h4>
				<p class="purpose">記下「誰、在哪一拍、做什麼、各自負責什麼」。</p>
				<figure class="diagram shot">
					<a href={actionShot} target="_blank" rel="noopener"
						><img src={actionShot} style:max-width="360px" alt="右邊欄的動作分頁：1 動作分頁、2 選人、3 標題（動作的名稱）、大類和辨識色、4 開始和長度、5 人和任務角色、6 新增動作按鈕。" /></a
					>
					<figcaption>圖 13　「動作」分頁。① 「動作」分頁　② 選人　③ 標題（動作的名稱）、大類、辨識色　④ 開始、長度　⑤ 人＋任務角色　⑥ 「新增動作」。</figcaption>
				</figure>
				<ol class="steps">
					<li><b>移播放頭：</b>移到動作開始的那一拍。動作表單是淡綠底、右上角標「新動作」，標題下面寫這個動作在哪一段。</li>
					<li>
						<b>選人：</b>按「選人」那一區的按鈕：「全隊」「全部底層」「全部上層」「這一拍沒在動作裡的人」「沿用上一個動作的人」（再按一次換更早的動作）；有選人時，「選人」兩個字的右邊多一個「不選人」。按了之後下面會寫選了誰（例如「選了『技巧·Lib』的 3 人」），選的人一改這行就收掉；選不到人時不改選的人，只寫原因（例如「這一拍每個人都在動作裡」）。也可以在場地上選取（見
						<a href="#formations">4.5</a>）。選到的人會出現在動作表單的「人」清單裡。同一時間已經在別的動作裡的人，名字旁邊標紅字「在『…』裡」，清單下面寫是誰，按旁邊的「拿掉這幾個人」就一次拿掉。還可以用「＋加人…」一個一個加（選項也標出同一時間在別的動作裡的人），或用「從別的動作複製人（連任務角色和組）…」把那個動作的人連任務角色一起帶進來（那個動作有分組的話，組也一起帶）。
					</li>
					<li><b>選大類：</b>技巧、金字塔、拋投、騰翻、跳躍、舞蹈、其他。</li>
					<li><b>填名稱：</b>寫在動作表單最上面的標題框（寫著「新動作的名稱，例如：Lib、籃拋」），可以不填，例如「Lib」「籃拋」。</li>
					<li><b>挑辨識色（可以不挑）：</b>同一個大類有好幾個動作時，幫它挑一個顏色，泳道上比較好認。選「照大類」就是用大類的顏色。</li>
					<li>
						<b>確認開始和長度：</b>開始已經照播放頭填好，播放頭移動時跟著變；你點進欄位或自己打過字之後就不再跟著變（播放中也一樣）。音樂段的長度預設 8 拍（1 個八拍）。音樂段的開始寫成「八拍-拍」，例如「3-5」，半拍加「&amp;」，例如「3-5&amp;」；長度寫幾拍，8 拍＝1 個八拍。口號段兩個都寫秒數。
					</li>
					<li><b>給任務角色：</b>加進來的人會先照全局角色填好：技巧、金字塔、拋投是全局底層填「底層」、全局上層填「上層」；騰翻一律填「騰翻」；跳躍、舞蹈、其他不填。換大類時，你沒改過的人跟著換成新大類的預設；還有人不是新大類的預設時，大類下面會出現「換成…的預設任務角色」，按了全部的人都換成新大類的預設（改已經有的動作時也一樣）。要細分就在每個人旁邊的任務角色選單改，例如主底、側底、上層、保護；選單裡每個角色旁邊有一句說明，意思也可以看 <a href="#words">2.1</a> 或按「名詞對照表」。<b>用鍵盤更快：</b>點第一個人的選單，按快捷鍵就選好、自動跳到下一個人，例如連按 2、3、4 就是主底、側底、上層。快捷鍵照名詞對照表的順序：1 底層、2 主底、3 側底、4 上層、5 中層、6 保護、7 前保、8 後保、9 接者、0 支撐、Q 騰翻；Backspace 是沒有任務。忘了就把滑鼠移到「名詞對照表」旁邊的「!」。</li>
					<li><b>備註：</b>有要提醒的就寫。</li>
					<li>技巧、金字塔、拋投有人是「上層」卻沒有人是底層（底層、主底、側底）時，人的清單下面出現黃字提醒。只提醒，不擋，照樣可以新增。</li>
					<li>按表單最下面藍色的「新增動作」（它黏在右邊欄底部，右邊欄很長也不用捲；還沒選人時按鈕是灰的，旁邊寫「還沒有人：先選人才能新增」），或在名稱、開始、長度欄按 Enter。泳道上每個人都多一條色條，播放頭跳到這個動作的結束；動作表單變成這個動作的內容（右上角的「新動作」換成「刪除動作」），可以接著改。要再新增別的動作，按動作表單<b>外面、上面</b>的「＋ 開新的動作表單」：它只是把動作表單清成空白的新動作，開始已經接在剛剛那個動作的結束，填好再按最下面藍色的「新增動作」才會加進去。新動作表單打到一半去點別的動作，回來時打的東西還在；按「復原」退掉剛新增的動作，新動作表單也回到新增前填的樣子。</li>
				</ol>
				<p class="note">
					做不出來時，動作表單下面會寫原因。最常見的：「動作不能跨段，要跨就拆成兩個」（在最後一段，後面沒有段可以拆，寫「超過這段的結尾，最多 N 拍」）「一個動作至少要有 1 個人」「某某 同一時間已經在『…』裡」。照原因改就好。
				</p>
				<p class="note">
					<b>「人」清單裡的顏色：</b>名字是藍底的是男生、粉紅底的是女生；名字前面的小圓寫「底」或「上」，是他在隊員名單裡的全局角色（不是這個動作的任務角色）。排任務角色時，一眼看得出誰適合撐、誰適合上去。
				</p>

				<h4>改動作</h4>
				<ol class="steps">
					<li>在泳道上點那個動作的色條。動作表單換成那個動作的內容。</li>
					<li>直接改任何欄位，改了馬上生效（不用按儲存）。</li>
					<li>要一次加好幾個人：在場地上選好人（Shift 點、框選，或用「選人」的按鈕），人的清單下面出現「＋ 把選的 N 人加進來」，按了就加進這個動作，任務角色照大類和全局角色先填好。</li>
					<li>改完要新增別的動作，按動作表單上面的「＋ 開新的動作表單」（或按 Esc）。還沒按「新增動作」的新動作表單按 Esc，只會收起開著的小選單，選好的人和任務角色不會清掉。</li>
					<li>轉接（例如三組 Lib 轉接成金字塔）：在動作表單備註下面按「＋ 接下一個動作」。動作表單變成新動作，開始接在這個動作的結束拍，播放頭也跳過去；大類、人、任務角色、組都帶過去，取好名字、改好長度，再按「新增動作」。新動作加第一個環節時，照帶過來的組分組。</li>
				</ol>

				<h4>在泳道上拖動作</h4>
				<ol class="steps">
					<li><b>換時間：</b>按住色條左右拖，放開。整個動作（所有人）一起移。</li>
					<li><b>改長度：</b>按住色條最右邊拖。</li>
				</ol>
				<p class="note">拖的時候會吸附：音樂段吸到半拍，口號段吸到 0.1 秒。放開時如果不合規則（例如跨段、撞到同一個人的別的動作），會還原，提示寫原因和「已還原」。</p>
				<p class="note">用 iPad：手指要先點一下色條選中它，才拖得動；沒選中的色條，手指一滑是捲動時間軸。站位縮圖也一樣。</p>

				<h4>刪動作</h4>
				<p class="purpose">點色條選到它，按動作表單上的「刪除動作」，或按 Delete（Mac 是 delete 鍵）。<b>不會先問，按了就刪</b>；場地下面跳出「已刪掉動作 …」，旁邊有「復原」，按了就救回來（跟按上方列的「復原」一樣）。焦點在動作表單裡（例如剛按過某人旁邊的 ×）、拍點格子或拍點小窗裡時，Delete 不會刪掉整個動作。動作有成功率的紀錄時才會先問，因為紀錄刪了救不回來（見 <a href="#practice">4.10</a>）。</p>

				<h4>自訂任務角色</h4>
				<ol class="steps">
					<li>按「名詞對照表」，在下面「新增自訂任務角色」填任務角色名稱和意思，按「新增任務角色」。或在任務角色選單選「＋自訂任務角色…」，會打開同一個地方；從那個人的選單打開、新增好的角色直接套給他。</li>
					<li>要改自訂任務角色的名稱或意思，在名詞對照表那一列直接改；動作裡的人、給這個角色的拍點會一起改成新名字。按那一列的垃圾桶刪掉；有動作用到時會先列出來問你，刪掉後那些人變成沒有任務，給這個角色的拍點也會刪掉。都可以復原。</li>
				</ol>
				<p class="note">自訂任務角色只存在這一支流程裡，排在名詞對照表最後面，快捷鍵接著是 W、E、R…。</p>

				<h4>看誰在上面、誰閒著</h4>
				<p class="purpose">
					<b>在上面：</b>任務角色是上層或中層的人，在那個動作的時間裡，場地上會畫在最上面、加黃框（左邊欄的圖例寫「正在上面」）。看的是任務角色，不是全局角色。<br />
					<b>閒著：</b>泳道上沒在動作裡的時間是灰色斜紋；播放頭那一拍閒著的人，泳道左邊的名字會變灰、標「閒」。
				</p>
			</section>

			<section id="cues">
				<h3 class="sec">4.7 拍點</h3>
				<p class="where">在<b>右邊欄「動作」分頁的動作表單</b>操作。先在泳道上點動作的色條，動作表單最下面就有<b>拍點格子</b>（「拍點」那一區）。還沒按「新增動作」的新動作沒有拍點格子。口號段不數拍，所以口號段的動作也沒有，動作表單上只寫「口號段不數拍，不能放拍點」。</p>
				<p>
					<b>拍點</b>是寫在動作裡某幾拍的提示：那幾拍要喊什麼、做什麼。就像紙本八拍表上寫的「down 2 拍、up 1 拍，第 7 拍上層 high V」。拍點分三種，各放在自己那一列（拍子列、步驟列、手位列）：
				</p>
				<ul class="plain">
					<li><b>拍子：</b>只有 down、up 兩個字，不能自己打。可以佔好幾拍，例如 down 2 拍，就是兩拍都在往下。</li>
					<li><b>步驟：</b>動作裡分出來的一段，例如「下手」「落地」「放」，也可以自己打字。可以佔好幾拍。動作的名字（例如 Lib）不是步驟。</li>
					<li><b>手位：</b>手臂擺的姿勢，例如 high V、T，也可以自己打字。只佔一拍。</li>
				</ul>
				<figure class="diagram shot">
					<a href={cuesShot} target="_blank" rel="noopener"
						><img src={cuesShot} style:max-width="300px" alt="動作表單裡的拍點格子和拍點小窗：1 數字格（一格一拍）、2 拍子列、步驟列、手位列、3 拍點小窗、4 選了幾拍和－、＋、5 給誰、6 三種拍點的按鈕、7 三個「清掉」。" /></a
					>
					<figcaption>
						圖 14　拍點格子。Lib 放了 down 2 拍、up 1 拍、下手 4 拍，第 7 拍給上層 high V；現在選了 4-5 到 4-6，跳出拍點小窗（這張是下面放不下、小窗在上面的樣子）。① 數字格，一格一拍　② 拍子列、步驟列、手位列　③ 拍點小窗　④ 選了哪幾拍，「－」「＋」少選、多選一拍　⑤ 給誰　⑥ 拍子、步驟、手位的按鈕，一種一列　⑦ 「清掉」。
					</figcaption>
				</figure>

				<h4>選拍</h4>
				<p class="purpose">先選要放在哪幾拍。動作碰到的每個八拍一排，前面的大數字是第幾個八拍，數字格裡寫第幾拍。動作外面的數字格變淡，不能選。選好，選的拍旁邊就跳出<b>拍點小窗</b>，放拍點的按鈕都在裡面，不用捲到下面。</p>
				<ol class="steps">
					<li><b>拖：</b>在數字格上按住，拖過那幾拍，放開。在拍子列、步驟列、手位列的空格上拖也可以。</li>
					<li><b>點：</b>點一個數字格選一拍。再按住 Shift 點另一個數字格，兩個之間的每一拍都選到（跟拖一樣）。</li>
					<li><b>＋、－：</b>在拍點小窗按「＋」多選一拍、「－」少選一拍。沒有 Shift（例如用 iPad）時用這個。用 iPad 拖的話，要從已經選到的拍開始拖；在沒選到的拍上滑，是捲動右邊欄。按的時候小窗不會跑走，只有上面的小尖角跟著選的拍移動。</li>
					<li>看小窗上「選了 4-5 到 4-6・2 拍」那一行，確認沒選錯。</li>
				</ol>
				<p class="note">拍點小窗平常在選的拍下面；畫面下面放不下時，改放在上面。按 Esc、按「✕」或點格子外面，就關掉；再點一下格子又會跳出來。</p>
				<p class="note">
					<b>方向鍵：</b>點過格子之後，按 ← → 把選取往左、往右移一拍；按著 Shift 再按 ← →，選取多一拍、少一拍。<br />
					<b>現在這一拍：</b>播放頭在這個動作裡時，播到的那一拍數字格底下有一條橘紅色粗線。<br />
					動作從半拍（&amp;）開始時，格子還是對齊音樂的整拍，跟你數的拍一樣。從 &amp; 開始或結束的拍點只塗半格，例如從「1&amp;」放到 2，第 1 格只塗後半。
				</p>

				<h4>放拍點</h4>
				<ol class="steps">
					<li><b>拍子：</b>在拍點小窗按「down」或「up」，選到的拍都放滿。放完，選取自動跳到下一拍，小窗不動，所以 down 放完直接按 up 就接上。</li>
					<li><b>步驟：</b>按「下手」「落地」「放」「上」「直下」「跳」，選到的拍都放滿。要別的字，在「自己打，例：抬腳」那個框打字，按 Enter 或「加入」。中文輸入法還在選字時按的 Enter 不算。框空著時「加入」按不下去。</li>
					<li><b>手位：</b>按 high V、low V、T、touchdown、K、L、diagonal、雙手並攏，或自己打字。只放在選到的第一拍。</li>
				</ol>
				<p class="note">
					自己打過的字會變成這支流程的按鈕，下次直接按。隊員打開你的流程檔也看得到。<br />
					同一列、同一個「給誰」，新放的拍點蓋到舊的，舊的會自動切短或拿掉。<br />
					點一個已經放好的拍點，就選回它佔的那幾拍（從 &amp; 開始的也照原本的範圍），「給誰」也換成它的，跳出拍點小窗，可以直接換字或清掉。
				</p>

				<h4>給誰</h4>
				<p class="purpose">
					放之前，在拍點小窗右上角的「給誰」選：「全部」（預設）、這個動作裡的任務角色（例如「上層」），或這個動作裡的某個隊員。給角色或隊員的拍點，字下面會寫給誰。給不同人的拍點可以在同一拍，例如全部 down、上層 high V，那一列會往下多開一層。
				</p>

				<h4>清掉拍點</h4>
				<p class="purpose">
					先選拍，再按拍點小窗裡那一列右邊的「清掉」：拍子那一列的只清拍子，步驟、手位也一樣。只清選到的拍裡的那一種，不管給誰，另外兩種不動。拍點有幾拍在選到的拍外面，外面那幾拍會留著。焦點在拍點格子或拍點小窗裡時按 Delete（Mac 是 delete 鍵），選到的拍裡三種拍點一起清掉（環節不動）。
				</p>

				<h4>拍點跟著動作走</h4>
				<p class="purpose">
					在泳道上拖動作換時間，拍點一起移動；拖半拍，拍點也晚半拍，落在 &amp;。改 BPM，拍點還在同一拍。刪動作，它的拍點一起刪。
				</p>

				<h4>會拿掉拍點的修改（都會先問）</h4>
				<p>下面這些修改會拿掉或切短拍點。畫面會先寫會拿掉幾個、列出是哪些，按「確定」才改；按「取消」就維持原樣。沒有拍點會被動到時，不會問。</p>
				<ul class="steps">
					<li>
						<b>動作變短：</b>在動作表單改「長度」，或在泳道上拉色條最右邊變短。跨出去一半的拍點切短，切完不到一拍的拿掉，整個在外面的拿掉。在泳道上按「取消」，色條回到原來的長度。
					</li>
					<li><b>拿掉人或角色：</b>在動作表單把一個人拿掉，或改了任務角色、動作裡沒有人是那個角色了，給他們的拍點會拿掉。</li>
					<li><b>刪隊員：</b>確認的訊息會多寫「會一起拿掉 N 個拍點」（見 <a href="#members">4.2</a>）。</li>
				</ul>

				<h4>在哪裡看到拍點</h4>
				<ul class="plain">
					<li>
						<b>泳道的色條：</b>有拍點的泳道會變高。動作名稱和任務角色在色條上半，下半是拍點的小長條，佔幾拍就畫多長：down 藍、up 綠、步驟淡橘加左邊粗線、手位粉紅小牌子。每個人的色條只畫給他的拍點（給全部的、給他任務角色的、給他本人的）。時間軸 ×1 時字會被切掉，放大到 ×3 左右看得比較清楚（見 <a href="#playback">4.4</a>）。
					</li>
					<li>
						<b>左邊欄的大字卡：</b>播放頭在有拍點的動作裡時，左邊欄（規則警告下面）出現一張<b>大字卡</b>：寫動作名字，現在這拍的步驟、拍子、手位用大字寫。佔好幾拍的寫到了第幾拍，例如「down 2/2」「下手 1/4」；給角色或隊員的，前面寫給誰，例如「上層 high V」。下面預告下一個拍點在哪一拍，例如「下一個 4-7：high V（上層）」。動作開始前一個八拍就先預告，動作結束就不見。播放、暫停、在八拍尺上點都看得到。同時有幾個動作有拍點，一個動作一張大字卡。
					</li>
					<li>
						<b>八拍表：</b>有拍點的八拍，那一列下面每個動作多一排：前面寫動作名字，後面分成 8 拍，字寫在它佔的那幾拍下面。佔好幾拍的畫成一條長條；跨到下一個八拍的，兩列都畫，字只寫在開始那一列。全隊的表寫給誰（給全部的不寫）；只印一個隊員時，只列給他的拍點。沒有拍點的動作照原本的寫法。
					</li>
					<li><b>流程檔：</b>拍點存在流程檔和草稿裡，隊員打開流程檔也看得到。</li>
				</ul>
			</section>

