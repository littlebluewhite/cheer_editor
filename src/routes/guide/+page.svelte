				</p>

				<h4>環節</h4>
				<p class="purpose">
					<b>環節</b>是一個動作裡要分開算成功率的一部分。種類只有五種：<b>上法、中段、轉接、下法、整體</b>（整個動作當成一個環節，例如一次拋投、一趟騰翻）。每個環節可以再取名字，例如上法「延伸」，畫面上寫成「上法 延伸」。同一個動作裡，每一組記的環節都一樣。
				</p>
				<p>音樂段的動作，環節標在動作裡的哪幾拍：</p>
				<ol class="steps">
					<li>在拍點格子選好拍（見 <a href="#cues">4.7</a>），要從整拍開始。拍點小窗最下面是「環節」那一排。</li>
					<li><b>加：</b>選種類、打名字（可以空著），按「加入」，加一個新環節標在這幾拍。</li>
					<li><b>標拍：</b>按那一排現有環節的名字，就把選的拍標給它。</li>
					<li>
						<b>刪：</b>按那一排的「清掉」，拿掉選到的拍上標的環節：只清到一部分的環節變短，拍被清光的環節就刪掉。把一個環節的拍全部標給別的環節，它也會刪掉。要刪的環節已經打過記號的話，小窗裡會先問，按「確定刪除」才刪。
					</li>
					<li>
						<b>改：</b>點拍點格子環節那一條上的色條，選到的就剛好是那個環節的拍，那一排下面多出「改環節」：點色塊換顏色（「照種類」是回到種類的顏色）、換種類、改名字。
					</li>
				</ol>
				<p>口號段不數拍，格子換成一句「口號段不數拍，不能放拍點」，下面直接一排「環節」，環節不用標拍：</p>
				<ol class="steps">
					<li><b>加：</b>選種類、打名字，按「加入」，加在最後。環節照加的先後排。</li>
					<li><b>改、刪：</b>點一個環節選它（再點一次是不選），下面多出「改環節」，可以改顏色、種類、名字；按「清掉」刪掉它，有記號的話先問。</li>
				</ol>
				<p class="note">
					音樂段的環節照標的拍的先後排。拍點格子多一條「環節」，那幾拍鋪上環節的顏色；泳道的色條上緣多一條環節顏色的細線；八拍表那一列也寫出環節。標拍不會改到拍點。動作變短、標的拍放不下時，跟拍點一起先問（見 <a href="#cues">4.7</a>）；拍被清光的環節會刪掉。
				</p>

				<h4>組</h4>
				<p class="purpose">
					<b>組</b>是一個動作裡一起做、一起算成功率的幾個人，例如一個技巧的主底、側底、後保、上層。16 個人分 4 組同時做一樣的技巧，就分成第 1 到第 4 組，每一組分開算。分組在<b>場地上</b>做。
				</p>
				<ol class="steps">
					<li>在泳道上點有環節的動作。場上這個動作的每個人，圓點右上角多一個<b>組號小圓</b>，塗那一組的顏色；沒分組的是灰色「?」。場地下面（「正面／裁判」那一排）出現<b>分組浮動列</b>。</li>
					<li>在場上選人（點、Shift＋點、框選，見 <a href="#formations">4.5</a>），浮動列寫「選了 3 人」。不在這個動作裡的人不算。</li>
					<li>按浮動列的組號（例如「2」）放進那一組；按「＋」放進新的一組；按「✕」拿出組（不分組）。選的人一次改好，按一次「復原」就退回去。</li>
					<li>電腦上選好人，也可以按<b>數字鍵</b>：1–9 放進那一組（最多到新的一組），0 拿出組。</li>
					<li>沒選人時按組號，就把那一組的人全選起來。有人沒分組時，浮動列最後寫「n 人沒分組」（n 是人數），按它把他們選起來。</li>
				</ol>
				<p class="note">
					組號從 1 連續往下排，不跳號：一組的人都拿出來，後面的組往前補號，紀錄還是跟著原來那一組。動作只有一組時，新加進來、沒帶組的人（例如用「＋加人…」加的）直接進第 1 組。動作表單「人」清單裡，每個人旁邊寫「第 n 組」或「沒分組」，只能看，不能改。<br />
					練習畫面寫組的名字，例如「第 1 組 小美」：後面是這組裡任務角色是上層的人（有好幾個就寫名單上第一個）；沒有上層就只寫「第 1 組」。
				</p>
				<p class="note">
					沒分到組的人不算成功率。<b>騰翻、跳躍的動作不分組，每個人自己算</b>：這兩個大類沒有組號小圓和分組浮動列，練習畫面一個人一張卡、一欄。
				</p>

				<h4>記錄頁：記分段練</h4>
				<p class="purpose"><b>分段練</b>是從流程裡拿一個動作（或連著的幾個）出來重複練很多次。記錄頁就是給分段練用的。</p>
				<figure class="diagram shot">
					<a href={recordShot} target="_blank" rel="noopener"
						><img src={recordShot} style:max-width="820px" alt="練習畫面的記錄頁：1 上方列的編排、練習切換、2 記錄和總表兩頁、日期、3 左邊要記的動作、4 一組一張卡（這次練整個或只練幾個環節，每個環節三顆記號按鈕）、5 這天的每一次和刪掉上一次、6 每天的成功率表。" /></a
					>
					<figcaption>
						圖 18　記錄頁。① 「編排」「練習」切換　② 「記錄」「總表」和日期　③ 要記的動作　④ 一組一張卡：這次練什麼、每個環節的 ✓ △ ✗　⑤ 這天的每一次、「刪掉上一次」　⑥ 每天的成功率。
					</figcaption>
				</figure>
				<ol class="steps">
					<li>按上方列的「練習」，練習畫面左上角按「記錄」。右上角的「日期」預設今天；練完才補記，先改日期（最晚選到今天）。手機、直拿的 iPad 上也可以記（見 <a href="#what">第 1 章</a>）。</li>
					<li>左邊是有記成功率、有環節的動作，照流程順序排，每個寫這天記了幾次和最弱的環節（例「最弱：下法 50%」）。點你們在練的動作。</li>
					<li>右邊每組一張卡（騰翻、跳躍每人一張）。先選「這次練」：「整個」，或「只練幾個環節」再勾要練的環節。動作只有一個環節時沒得選，一定是整個做。</li>
					<li>
						那一組做完一次，照順序在每個環節按 ✓、△ 或 ✗。按錯了，再按一次亮著的那顆就取消。<br />
						<b>「整個」：</b>都按好了，按卡片下面的「存這一次」才存。中途失敗就在那個環節按 ✗，再按「存這一次」，後面的環節空著。跳過了前面的環節時，按存之前卡上就會寫「跳過了前面的環節，存了會記成「只練幾個環節」，不算進整次成功率」。<br />
						<b>「只練幾個環節」：</b>要練的環節都按了，<b>就自動存成一次</b>，不用按存；按到 ✗ 也馬上存，後面的環節空著。<br />
						存好了，卡上寫「已存」。
					</li>
					<li>卡片下面列出這組這天的每一次，例如「✓✗·」（· 是空著的環節）；全上記的那幾次用虛線框分出來。記錯了，按「刪掉上一次」，刪掉這張卡這天最後記的那一次分段練（全上記的不會被刪到）。卡上寫「已刪掉」，旁邊有「救回」，10 秒內按它就拿回來（滑鼠在上面時不會收起來）。</li>
				</ol>
				<p class="note">
					按到一半、還沒存的記號只在那張卡上：換動作、換頁就不算了。救回只在刪掉後 10 秒內；過了就救不回來（刪掉上一次不算復原的一步）。「整個」「只練幾個環節」選了會一直留著，下一次不用再選。<br />
					卡片下面是「每天的成功率」：一天一列，最後一列合計。選「看哪一組」（騰翻、跳躍是「看哪一個人」）只看那一組。格子大字是成功率，小字是完成率和次數。
				</p>
				<p class="note">
					<b>練習畫面沒有「復原」「重做」。</b>復原、重做只退編排的修改，在練習畫面看不到退了什麼，所以要回「編排」才按得到；記一次、刪掉上一次都不算一步，復原不會動到紀錄。要刪記錄錯的那一次分段練，按「刪掉上一次」。不過，在編排復原到還沒有某個環節、某一組，或動作還沒有環節的時候，對不上的紀錄會跟著不見，重做也拿不回來。<br />
					練習畫面的快捷鍵只有存檔：空白鍵不會播放，Delete 不會刪東西，⌘Z／Ctrl+Z 也不會復原。
				</p>

				<h4>總表</h4>
				<p class="purpose">一眼看全部動作、每組、每個環節的成功率，找出最不穩的地方。在練習畫面左上角按「總表」。</p>
				<figure class="diagram shot">
					<a href={summaryShot} target="_blank" rel="noopener"
						><img src={summaryShot} style:max-width="820px" alt="練習畫面的總表：1 篩選（期間、練法、大字看）、2 記一次全上按鈕、3 一組一個環節的格子（顏色看比例）、4 合計那一欄、5 整次那一列、6 點格子打開的明細。" /></a
					>
					<figcaption>圖 19　總表。① 篩選：期間、練法、大字看　② 「＋ 記一次全上」　③ 一組、一個環節的格子　④ 合計　⑤ 整次　⑥ 明細。</figcaption>
				</figure>
				<ul class="steps">
					<li>
						<b>一個動作一張表：</b>一列一個環節，最後一列「整次」；一欄一組（騰翻、跳躍一欄一個人），最後一欄「合計」（全部組的次數加起來算，不是平均）。格子大字是比例，小字是幾次；沒有紀錄寫「—」。
					</li>
					<li><b>顏色：</b>90% 以上綠色、75% 到 89% 黃色、不到 75% 紅色。數字一定寫出來，分不出顏色也看得懂。</li>
					<li>
						<b>篩選：</b>「期間」選上面選的那一天（按鈕寫日期，例如「11/5」，是今天就寫「今天 11/5」）、最近 7 天（上面選的日期和前 6 天）或全部；「練法」選全部、只看全上、只看分段練；「大字看」選成功率或完成率，「整次」那一列一律是整次成功率（大字看完成率時，那一列的標題寫「整次成功率」）。換頁回來，篩選回到預設。
					</li>
					<li><b>明細：</b>點一組的格子，右邊出現這組、這個環節每天的每一次記號，全上記的標「全上」。明細照跟格子一樣的期間、練法篩選。按「關閉」收起。合計和整次的格子不能點。</li>
				</ul>

				<h4>記一次全上</h4>
				<p class="purpose"><b>全上</b>是整支流程從頭到尾連著做一遍。全上記的次可以跟分段練分開看（「練法」篩選）。</p>
				<ol class="steps">
					<li>在記錄頁最上面或總表按「＋ 記一次全上」。每個有記成功率的動作一張表，一組一欄、一個環節一格，每格先是 ✓。</li>
					<li>點出錯的格子：點一下變 △，再點變 ✗，再點回 ✓。一組在某個環節是 ✗，它後面的環節就空著。</li>
					<li>中途停了，在停下來的那個動作按「後面都沒做」，它後面的動作這次都不記；或在沒做到的動作按它的「沒做（停了）」，一個一個拿掉。</li>
					<li>按「存這次全上」：每組在每個動作各存成一次，都算整個做；存好了寫「已存這次全上」。按「取消」不存；改過格子的話，會先問你。</li>
				</ol>
				<p class="note">全上記的次也會出現在記錄頁卡片的「這天的每一次」，用虛線框分出來。卡片上的「刪掉上一次」只刪分段練記的，不會刪到全上記的。全上記錯了，在記錄頁最上面按「刪掉上一次全上」：這天最後存的那次全上整次刪掉（每個動作、每組的都一起刪）。寫「已刪掉」，旁邊有「救回」，10 秒內按它就整次拿回來。</p>

				<h4>成功率、完成率、整次成功率怎麼算</h4>
				<ul class="steps">
					<li><b>成功率：</b>一個環節有打記號的次數裡，成功（✓）佔多少。小失誤不算成功。例：✓ ✓ △ ✗ 是 2/4＝50%。</li>
					<li><b>完成率：</b>成功加小失誤佔多少，也就是沒失敗的比例。上面的例子是 3/4＝75%。</li>
					<li>
						<b>整次成功率：</b>整個做的次裡，每個環節都成功的次佔多少。中途失敗的也算一次（沒成功）；只練幾個環節的次不算；那一次之後才加的環節不看。
					</li>
					<li>空著的環節（中途失敗之後的、這次沒練的）不算進成功率，也不算進完成率。% 都四捨五入到整數。</li>
				</ul>

				<h4>會清掉紀錄的修改（都會先問）</h4>
				<p>下面這些修改會清掉已經記的紀錄。畫面會先寫會清掉幾次，按「確定」才改；按「取消」就維持原樣。沒有紀錄會被動到時，不會問。</p>
				<ul class="steps">
					<li><b>刪掉動作的最後一個環節、刪動作：</b>那個動作的紀錄全部清掉。有紀錄的動作，按「刪除動作」或 Delete 也會先問。</li>
					<li><b>刪環節：</b>這個環節的記號清掉；一次裡只有這個環節有記號的，那一次整個清掉。</li>
					<li>
						<b>動作換了人：</b>在動作表單拿掉人，或在場上改組，讓某一組沒人了；騰翻、跳躍的動作拿掉人；或大類在有分組的和騰翻、跳躍之間換（變成每個人自己算）。那些組、那些人的紀錄清掉。
					</li>
					<li><b>段縮短、刪隊員：</b>被刪掉的動作的紀錄，和那個隊員所在的組、他自己的紀錄，一起清掉；確認的訊息會多寫清掉幾次紀錄。</li>
				</ul>
				<p>下面兩種情況，畫面會讓你三選一：「保留舊紀錄」（紀錄留著，算在現在的人身上）、「清掉重算」（清掉那些組的紀錄，從頭記）、「取消」（不改）。</p>
				<ul class="steps">
					<li><b>有紀錄的組換了人：</b>組裡還有人，但不是原來那幾個。</li>
					<li><b>有紀錄的隊員改名字：</b>可能是候補換上場。</li>
				</ul>
				<p class="note">清掉的紀錄，按「復原」救不回來。</p>
			</section>

