				<h3 class="sec">4.8 流程設定</h3>
				<p class="where">按<b>上方列的「流程設定」</b>。</p>
				<ul class="plain">
					<li><b>流程名字：</b>改名字，最多 40 個字。</li>
					<li><b>場地：</b>寫這支流程的場地是幾條、直放或橫放，只能看，不能改（建好之後不能換）。</li>
					<li>
						<b>規則警告（只提醒，不擋）：</b>預設打勾。打勾時，口號段加起來少於第一個數字，或音樂段、整支流程超過後兩個數字，左邊欄就出現規則警告：「口號段最少（秒）」（所有口號段加起來，預設 30）、「音樂段加起來最多（秒）」（預設 120）、「整支流程最多（秒）」（預設 180）。照你要參加的比賽規則改；不要提醒就取消打勾。
					</li>
					<li>
						<b>標記：</b>場上圓點、泳道、隊員名單、八拍表上寫的字。預設是「號碼」（名單第幾個）；選「開頭字（名字的第一個字）」就寫每個人名字的第一個字。開頭字一樣的人會再多帶一個字分開，例如王小明、王大華寫成「王小」「王大」；名字後面是數字的，數字整串算一個字，例如新人1 到新人10 寫成「新1」到「新10」。下面會列出每個人的標記，不喜歡就到「隊員」改名字（例如用暱稱）。標記存在流程檔裡，隊員打開看到的一樣。
					</li>
				</ul>
				<p class="note">還沒有任何段時不會提醒。加了音樂段、還沒加口號段時，會看到「口號段共 0.0 秒，少於 30 秒」，這是正常的。口號段加起來到最少秒數，警告就會消失：新的口號段預設只有 10 秒，所以加了一段、還不到 30 秒時，警告會變成「口號段共 10.0 秒，少於 30 秒」，要把口號段加長，或再加口號段。</p>
			</section>

